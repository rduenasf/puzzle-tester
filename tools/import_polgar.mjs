// Builds polgar.js from problems.json of https://github.com/denialromeo/4462-chess-problems
// (the checkmate problems of László Polgár's "Chess: 5334 Problems, Combinations and Games").
//
//   node tools/import_polgar.mjs path/to/problems.json
//
// Every problem is checked with the same solver the app uses: the book line must be
// legal, end in checkmate, and its first move must force mate within the labelled
// number of moves. Problems that fail are left out and listed on stderr.
import { readFileSync, writeFileSync } from 'node:fs';
import { Chess } from '../vendor/chess.js';
import { allRepliesLose } from '../matesolver.js';

const N = { 'Mate in One': 1, 'Mate in Two': 2, 'Mate in Three': 3 };

const src = JSON.parse(readFileSync(process.argv[2], 'utf8')).problems;
const out = [], bad = [];
const t0 = Date.now();
for (const p of src) {
  const mate = N[p.type];
  const why = (() => {
    if (!mate) return `unknown type ${p.type}`;
    let g;
    try { g = new Chess(p.fen); } catch (e) { return `bad FEN: ${e.message}`; }
    const line = p.moves.split(';').map((m) => m.replace('-', ''));
    if (line.length !== 2 * mate - 1) return `line has ${line.length} plies`;
    for (const m of line) {
      try { g.move({ from: m.slice(0, 2), to: m.slice(2, 4), promotion: m[4] }); } catch { return `illegal move ${m}`; }
    }
    if (!g.isCheckmate()) return 'line does not end in mate';
    const h = new Chess(p.fen);
    h.move({ from: line[0].slice(0, 2), to: line[0].slice(2, 4), promotion: line[0][4] });
    if (!(h.isCheckmate() || (mate > 1 && allRepliesLose(h, mate - 1)))) return 'first move does not force mate';
    out.push({ id: `polgar-${p.problemid}`, title: `Polgár #${p.problemid}`, mate, fen: p.fen, line });
    return null;
  })();
  if (why) bad.push(`#${p.problemid}: ${why}`);
}

const body = out.map((p) => '  ' + JSON.stringify(p)).join(',\n');
writeFileSync(new URL('../polgar.js', import.meta.url),
`// Generated by tools/import_polgar.mjs. Do not edit by hand.
// Checkmate problems from László Polgár, "Chess: 5334 Problems, Combinations and Games" (1994),
// as collected in https://github.com/denialromeo/4462-chess-problems.
// Each one was checked: the line is legal, ends in mate, and its first move forces mate in \`mate\`.
export const POLGAR = [
${body},
];
`);
const count = (n) => out.filter((p) => p.mate === n).length;
console.log(`kept ${out.length}/${src.length} (mate in 1: ${count(1)}, 2: ${count(2)}, 3: ${count(3)}) in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
if (bad.length) console.error(`dropped ${bad.length}:\n` + bad.join('\n'));
